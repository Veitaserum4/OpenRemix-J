"""Generates plugins/d3d9/src/profiles.cpp from Remix Plus's per-game defaults,
keeping the options the plugin reads:
  python gen_profiles.py <dxvk-remix>/src/util/config/config.cpp plugins/d3d9/src/profiles.cpp"""
import re
import sys

source = sys.argv[1]
output = sys.argv[2]
text = open(source, encoding='utf-8').read()

KEYS = {
    'rtx.uiTextures', 'rtx.skyBoxTextures', 'rtx.lightmapTextures', 'rtx.ignoreTextures',
    'rtx.useObsoleteHashOnTextureUpload', 'rtx.zUp', 'rtx.leftHandedCoordinateSystem', 'rtx.sceneScale',
    'rtx.worldSpaceUiTextures', 'rtx.worldSpaceUiBackgroundTextures', 'rtx.skyDrawcallIdThreshold',
    'rtx.skyMinZThreshold', 'rtx.viewModel.enable', 'rtx.viewModel.maxZThreshold',
    'rtx.geometryAssetHashRuleString', 'rtx.orthographicIsUI', 'rtx.allowCubemaps', 'rtx.fusedWorldViewMode',
    'rtx.decalTextures', 'rtx.dynamicDecalTextures', 'rtx.singleOffsetDecalTextures', 'rtx.nonOffsetDecalTextures',
    'rtx.particleTextures', 'rtx.beamTextures', 'rtx.terrainTextures', 'rtx.animatedWaterTextures',
    'rtx.hideInstanceTextures', 'rtx.playerModelTextures', 'rtx.playerModelBodyTextures',
    'rtx.ignoreBakedLightingTextures', 'rtx.ignoreAlphaOnTextures', 'rtx.cutoutTextures',
    'rtx.smoothNormalsTextures', 'rtx.hairCardTextures', 'rtx.ignoreLights', 'rtx.enableAlphaBlend',
    'rtx.enableAlphaTest', 'rtx.preTransformedVerticesIsUI', 'rtx.recomputeTextureHashOnWrite',
}

block_re = re.compile(r'\{\s*R"\((.*?)\)"\s*,\s*\{\{(.*?)\}\}\s*\}', re.S)
entry_re = re.compile(r'\{\s*"(rtx\.[^"]+)"\s*,\s*((?:"[^"]*"\s*)+)\}', re.S)
profiles = []
for match in block_re.finditer(text):
    regex, body = match.group(1), match.group(2)
    # Comments between a list's pieces (the values hold no "//").
    body = re.sub(r'//[^\n]*', '', body)
    lines = []
    for entry in entry_re.finditer(body):
        key = entry.group(1)
        if key not in KEYS:
            continue
        value = ''.join(re.findall(r'"([^"]*)"', entry.group(2)))
        lines.append(f'{key} = {value}')
    if lines:
        profiles.append((regex, lines))

def literal(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'

out = []
out.append('// Generated by plugins/d3d9/scripts/gen_profiles.py from Remix Plus (RemixProjGroup/dxvk-remix)')
out.append('// src/util/config/config.cpp: the per-game defaults among the options the plugin')
out.append('// reads, as rtx.conf lines. MIT license (dxvk-remix). Do not edit by hand.')
out.append('#include "profiles.h"')
out.append('')
out.append('namespace openremix::d3d9 {')
out.append('')
out.append('const std::vector<Profile> &profiles() {')
out.append('  static const std::vector<Profile> list = {')
for regex, lines in profiles:
    out.append(f'      {{R"({regex})",')
    body = '\n'.join(lines) + '\n'
    chunks = [body[i:i + 100] for i in range(0, len(body), 100)]
    out.append('       ' + '\n       '.join(literal(c) for c in chunks) + '},')
out.append('  };')
out.append('  return list;')
out.append('}')
out.append('')
out.append('} // namespace openremix::d3d9')
open(output, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print(f'{len(profiles)} profiles:', ', '.join(r for r, _ in profiles))
